export type CaseTone = 'pass' | 'fail' | 'return' | 'neutral';

export interface CaseEvent {
  node: number;
  result: CaseTone;
  message: string;
  label?: string;
}

export interface ILoopRound {
  id: string;
  name: string;
  state: string;
  stateLabel: string;
  focus: string;
  summary: Array<[CaseTone, string]>;
  finalLabel: string;
  finalMessage: string;
  events: CaseEvent[];
}

const event = (
  node: number,
  result: CaseTone,
  message: string,
  label = '',
): CaseEvent => ({ node, result, message, label });

